/* ---- terrain heightfield with the hill ---- */

const LINE_X = helixEndX; // x of the bridge/hill line (-880)
const landY = roadY(GAP1);
const GROUND_DROP = 5; // ground sits this far under grounded road
const FLANK_START = BRIDGE.lip - 250; // hill's front face starts rising here, just under the kicker
function hillLine(z) {
  // height along the bridge/hill line, as a function of z
  const b = z - TOWER.cz;
  if (b <= FLANK_START) return 0;
  if (b < BRIDGE.land) {
    const u = (b - FLANK_START) / (BRIDGE.land - FLANK_START);
    // a real drop under the gap, but never steeper than ~31° so a kart that
    // falls short can still drive up onto the hill road
    return (landY - GROUND_DROP) * (0.6 * u + 0.4 * smooth(u));
  }
  if (b <= BRIDGE.hillEnd) return roadY(S_BRIDGE + b) - GROUND_DROP;
  return 0;
}
function naturalH(x, z) {
  const d = Math.abs(x - LINE_X);
  const g = 1 - smooth((d - 250) / 800);
  return Math.max(-GROUND_DROP, -GROUND_DROP + (hillLine(z) + GROUND_DROP) * g);
}
// Road samples that sit on the ground (hill road, U-turn, home & start straight)
const groundFrames = frames.filter((f) => f.s >= GAP1 || f.s <= S_HELIX0 + 1);
function terrainH(x, z) {
  let h = naturalH(x, z);
  // Under grounded road the ground sits exactly GROUND_DROP below it, blending
  // back to the natural shape over 180 units. The hill-road frames only act
  // past the landing edge so they don't build a shelf under the gap.
  let best = null;
  let bestD = Infinity;
  for (const f of groundFrames) {
    if (f.s >= GAP1 && f.s < S_UTURN && z < TOWER.cz + BRIDGE.land - 1) continue;
    const dx = x - f.x;
    const dz = z - f.z;
    const d2 = dx * dx + dz * dz;
    if (d2 < bestD) {
      bestD = d2;
      best = f;
    }
  }
  if (best) {
    const d = Math.sqrt(bestD);
    const t = smooth((d - best.w - 120) / 180);
    h = lerp(best.y - GROUND_DROP, h, t);
  }
  return h;
}

